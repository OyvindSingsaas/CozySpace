#!/usr/bin/env python3
"""Convert the clips in sounds/ to small web audio and pack them into data/sounds.js.

The page can't read audio files directly when opened from disk (browsers block that), so the
clips travel inside a script, like the ephemeris. Needs ffmpeg.

Usage:  python3 scripts/pack_sounds.py
Edit CLIPS below to add sounds: key -> (file in sounds/, credit).
"""
import base64, json, os, subprocess, sys, tempfile

CLIPS = {
    "motherChild": ("Kiss, Mother and Child.wav", "Voyager Golden Record, 'Sounds of Earth': kiss, mother and child (NASA/JPL, 1977)"),
    "mars": ("mars.wav", "Sound on Mars, recorded by Perseverance's SuperCam microphone. NASA/JPL-Caltech/LANL/CNES/CNRS/ISAE-SUPAERO"),
    "moonStep": ("moon.mp3", "Apollo 11: Neil Armstrong, 'That's one small step for man...' (NASA, 20 July 1969)"),
    "perseus": ("sonify5_perseus.mp3", "Sonification of the supermassive black hole in the Perseus galaxy cluster. NASA/CXC/SAO/K. Arcand, M. Russo & A. Santaguida. CC BY-NC 3.0"),
    # "whale": ("Whales.wav", "Voyager Golden Record: humpback whale song (Roger Payne recordings)"),
}

def encode(src):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "o.mp3")
        # mono, gentle loudness normalisation, short fades so nothing clicks
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-ac", "1", "-ar", "32000",
                        "-af", "loudnorm=I=-20:TP=-2:LRA=11,afade=t=in:d=0.15,areverse,afade=t=in:d=0.6,areverse",
                        "-b:a", "56k", out], check=True)
        return open(out, "rb").read()

def main():
    packed, credits = {}, {}
    for key, (name, credit) in CLIPS.items():
        src = os.path.join("sounds", name)
        if not os.path.exists(src):
            print(f"{key:12} missing: {src}", file=sys.stderr); continue
        data = encode(src)
        packed[key] = "data:audio/mpeg;base64," + base64.b64encode(data).decode()
        credits[key] = credit
        print(f"{key:12} {len(data) / 1024:6.1f} kB  <- {name}")
    with open("data/sounds.js", "w") as f:
        f.write("// generated by scripts/pack_sounds.py from sounds/. see sounds/CREDITS.md\n")
        f.write("window.SOUNDS = " + json.dumps(packed) + ";\n")
        f.write("window.SOUND_CREDITS = " + json.dumps(credits) + ";\n")
    print("wrote data/sounds.js")

if __name__ == "__main__":
    main()
