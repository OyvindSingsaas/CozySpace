#!/usr/bin/env python3
"""Fetch a year of geocentric positions from JPL Horizons and write data/ephemeris.js.

For each object: ecliptic longitude (deg) and distance from Earth (km), every STEP days.
Objects whose published ephemeris ends early are fetched up to that end date; the page
falls back to its own approximations outside the covered range.

Usage:  python3 scripts/fetch_ephemeris.py [--days 365] [--step 2]
Stdlib only (falls back to `curl` if Python's SSL certificates aren't set up, common on macOS).
"""
import argparse, json, math, re, subprocess, sys, time, urllib.parse, urllib.request
from datetime import date, datetime, timedelta, timezone

API = "https://ssd.jpl.nasa.gov/api/horizons.api"
OBJECTS = {  # page key -> Horizons COMMAND
    "MERC": "199", "VENUS": "299", "MARS": "499", "JUP": "599", "SAT": "699", "URA": "799", "NEP": "899", "PLU": "999",
    "VGR1": "-31", "VGR2": "-32", "NHPC": "-98", "SPP": "-96", "STA": "-234", "SOHO": "-21", "ACE": "-92",
    "WIND": "-8", "DSCO": "-78", "JWST": "-170", "EUCL": "-680", "JNO": "-61", "EURC": "-159", "JUCE": "-28",
    "PSYC": "-255", "LUCY": "-49", "BEPI": "-121", "SOLO": "-144",
}

def get(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "CozySpace"}), timeout=60) as r:
            return r.read().decode()
    except urllib.error.URLError as e:
        if "CERTIFICATE" not in str(e): raise
        return subprocess.run(["curl", "-sS", "--max-time", "60", url], check=True, capture_output=True, text=True).stdout

def query(cmd, start, stop, step):
    params = {"format": "json", "COMMAND": f"'{cmd}'", "EPHEM_TYPE": "VECTORS", "CENTER": "'500@399'",
              "REF_PLANE": "ECLIPTIC", "START_TIME": f"'{start}'", "STOP_TIME": f"'{stop}'",
              "STEP_SIZE": f"'{step} d'", "VEC_TABLE": "'1'", "OUT_UNITS": "'KM-S'", "CSV_FORMAT": "YES"}
    j = json.loads(get(API + "?" + urllib.parse.urlencode(params, quote_via=urllib.parse.quote)))
    return j.get("result", "") or j.get("error", "")

def parse(text):
    if "$$SOE" not in text: return None
    rows = []
    for line in text.split("$$SOE", 1)[1].split("$$EOE", 1)[0].strip().splitlines():
        f = [x.strip() for x in line.split(",")]
        x, y, z = float(f[2]), float(f[3]), float(f[4])
        rows.append([round(math.degrees(math.atan2(y, x)) % 360, 2), float(f"{math.sqrt(x*x + y*y + z*z):.5g}")])
    return rows

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=365)
    ap.add_argument("--step", type=int, default=2)
    ap.add_argument("--out", default="data/ephemeris.js")
    a = ap.parse_args()
    start = date.today() - timedelta(days=7)
    stop = start + timedelta(days=a.days)
    out = {"start": start.isoformat() + "T00:00:00Z", "stepDays": a.step,
           "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "objects": {}}
    for key, cmd in OBJECTS.items():
        end = stop
        for _ in range(2):
            text = query(cmd, start, end, a.step)
            rows = parse(text)
            if rows is not None: break
            m = re.search(r"after A\.D\. (\d{4}-[A-Z]{3}-\d{2})", text)
            if not m: break
            end = datetime.strptime(m.group(1).title(), "%Y-%b-%d").date() - timedelta(days=1)
            if end <= start + timedelta(days=a.step): rows = None; break
        if rows and len(rows) >= 4:                      # need a few points to interpolate; ~1 week back is "now"
            out["objects"][key] = rows
            print(f"{key:6} {len(rows):4} points  now {rows[min(3, len(rows) - 1)][1] / 299792.458 / 3600:8.3f} light-hours")
        elif rows:
            print(f"{key:6} skipped: ephemeris ends too soon ({len(rows)} points)", file=sys.stderr)
        else:
            print(f"{key:6} skipped: {' '.join(text.split())[:100]}", file=sys.stderr)
        time.sleep(0.3)
    with open(a.out, "w") as f:
        f.write("// generated by scripts/fetch_ephemeris.py from JPL Horizons. geocentric ecliptic [longitude deg, distance km]\n")
        f.write("window.EPHEMERIS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(f"wrote {a.out}")

if __name__ == "__main__":
    main()
